// Local snapshot of opsique-mono-harness UI 0.1. No dependency on its checkout.
import { readFileSync, writeFileSync } from 'node:fs';
import Ajv from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
const contract = new URL('../packages/shared/ui-contract/', import.meta.url);
const output = new URL('../packages/shared/src/ui/', import.meta.url);
const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
ajv.addSchema(JSON.parse(readFileSync(new URL('spec.schema.json', contract))), 'spec.schema.json');
const validate = ajv.compile(JSON.parse(readFileSync(new URL('document.schema.json', contract))));
const code = standaloneCode(ajv, validate).replace(
  /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
  'const $1 = value => [...value].length;',
);
writeFileSync(
  new URL('schema.generated.ts', output),
  '// @ts-nocheck\n// Generated by scripts/generate-ui-schema.mjs. Do not edit.\n' + code + '\n',
);
const catalog = JSON.parse(readFileSync(new URL('catalog.json', contract)));
writeFileSync(
  new URL('catalog.generated.ts', output),
  '// Generated by scripts/generate-ui-schema.mjs. Do not edit.\nexport default ' +
    JSON.stringify(catalog) +
    ' as const;\n',
);
